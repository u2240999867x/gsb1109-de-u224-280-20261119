from dataclasses import dataclass, field
from typing import Any

from dataset.util import SQLWriteValue, WriteRow


@dataclass
class UpdateTarget:
    """A single row expected to be modified by a planned correction.

    ``primary_key`` holds the tuple of primary key values identifying the
    row. ``before`` is the simulated state of the full row just before the
    correction is applied (including the effects of any earlier corrections
    in the same batch). ``changes`` are the column values the correction
    will write.
    """

    primary_key: tuple[Any, ...]
    before: dict[str, Any]
    changes: dict[str, SQLWriteValue]


@dataclass
class UpdatePlanEntry:
    """The simulated outcome of applying one correction row."""

    row: WriteRow
    keys: list[str]
    targets: list[UpdateTarget] = field(default_factory=list)

    @property
    def primary_keys(self) -> list[tuple[Any, ...]]:
        """Primary keys of the rows this correction is expected to affect."""
        return [target.primary_key for target in self.targets]


@dataclass
class UpdatePlan:
    """A preview of a batch of keyed corrections against a table.

    Generated by :py:meth:`Table.preview_update_many
    <dataset.Table.preview_update_many>` and applied atomically by
    :py:meth:`Table.apply_update_plan <dataset.Table.apply_update_plan>`.
    """

    table_name: str
    keys: list[str]
    entries: list[UpdatePlanEntry] = field(default_factory=list)

    @property
    def affected_primary_keys(self) -> list[tuple[Any, ...]]:
        """All primary keys the batch is expected to touch, in order."""
        seen: list[tuple[Any, ...]] = []
        for entry in self.entries:
            for primary_key in entry.primary_keys:
                if primary_key not in seen:
                    seen.append(primary_key)
        return seen

    @property
    def is_noop(self) -> bool:
        """Check if no correction in the batch matched any rows."""
        return all(not entry.targets for entry in self.entries)
