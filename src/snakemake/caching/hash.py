import asyncio
import json
import hashlib
from typing import TYPE_CHECKING

from snakemake import script
from snakemake import wrapper
from snakemake.exceptions import WorkflowError

if TYPE_CHECKING:
    from snakemake.jobs import Job

# ATTENTION: increase version number whenever the hashing algorithm below changes!
# Note: role-aware hashing of named inputs does not change the hash of workflows
# that only use unnamed inputs, hence the version is kept at 0.1 for backwards
# compatibility with existing cache entries of such workflows.
__version__ = "0.1"


class ProvenanceHashMap:
    def __init__(self):
        self._hashes = dict()

    async def get_provenance_hash(self, job: Job):
        versioned_hash = hashlib.sha256()
        # Ensure that semantic version changes in this module
        versioned_hash.update((await self._get_provenance_hash(job)).encode())
        versioned_hash.update(__version__.encode())
        return versioned_hash.hexdigest()

    async def _get_provenance_hash(self, job: Job):
        """
        Recursively calculate hash for the output of the given job
        and all upstream jobs in a blockchain fashion.

        This is based on an idea of Sven Nahnsen.
        Fails if job has more than one output file. The reason is that there
        is no way to generate a per-output file hash without generating the files.
        This hash, however, shall work without having to generate the files,
        just by describing all steps down to a given job.
        """
        if job in self._hashes:
            return self._hashes[job]

        workflow = job.dag.workflow
        h = hashlib.sha256()

        # Hash shell command or script.
        if job.is_shell:
            # We cannot use the formatted shell command, because it also contains threads,
            # resources, and filenames (which shall be irrelevant for the hash).
            h.update(job.rule.shellcmd.encode())
        elif job.is_script:
            _, source, _, _, _ = script.get_source(
                job.rule.script,
                job.rule.workflow.sourcecache,
                basedir=job.rule.basedir,
                wildcards=job.wildcards,
                params=job.params,
            )
            h.update(source.encode())
        elif job.is_notebook:
            _, source, _, _, _ = script.get_source(
                job.rule.notebook,
                job.rule.workflow.sourcecache,
                basedir=job.rule.basedir,
                wildcards=job.wildcards,
                params=job.params,
            )
            h.update(source.encode())
        elif job.is_wrapper:
            _, source, _, _, _ = script.get_source(
                wrapper.get_script(
                    job.rule.wrapper,
                    sourcecache=job.rule.workflow.sourcecache,
                    prefix=workflow.workflow_settings.wrapper_prefix,
                ),
                job.rule.workflow.sourcecache,
                basedir=job.rule.basedir,
                wildcards=job.wildcards,
                params=job.params,
            )
            h.update(source.encode())

        # Hash params.
        for key, value in sorted(job.params._allitems()):
            if key is not None:
                h.update(key.encode())
            # If this raises a TypeError, we cannot calculate a reliable hash.
            try:
                h.update(json.dumps(value, sort_keys=True).encode())
            except TypeError as e:
                raise WorkflowError(
                    "Rule {} cannot be cached, because params "
                    "are not JSON serializable. "
                    "Consider converting them into a suitable format "
                    "if you are sure that caching is necessary. "
                    "Otherwise, deactivate caching for this rule "
                    "by removing it from the --cache command line argument "
                    "or removing the cache: true directive from the rule itself.".format(
                        job.rule.name
                    ),
                    e,
                )

        # Hash input files that are not generated by other jobs.
        omit_storage_content = job.rule.cache and job.rule.cache.omit_storage_content

        def is_dependency(f):
            return any(
                f in depfiles for depfiles in job.dag.dependencies[job].values()
            )

        async def get_checksum(f):
            if f.is_storage and omit_storage_content:
                return f.storage_object.query
            return await f.checksum(force=True)

        # Keep the role (input name) alongside each primary input. Named inputs
        # are hashed together with their role, so swapping two differently named
        # inputs changes the provenance hash even if both contents stay the same.
        # Unnamed inputs retain the historical order-independent behavior of
        # hashing sorted checksums, which keeps existing cache entries of
        # workflows without named inputs valid.
        role_inputs = []
        for name, item in job.input._allitems():
            files = list(item) if isinstance(item, list) else [item]
            for f in files:
                if not is_dependency(f):
                    role_inputs.append((name, f))

        checksums = await asyncio.gather(
            *[get_checksum(f) for _, f in role_inputs]
        )

        unnamed_checksums = sorted(
            checksum
            for (name, _), checksum in zip(role_inputs, checksums)
            if name is None
        )
        for file_hash in unnamed_checksums:
            h.update(file_hash.encode())

        named_checksums = sorted(
            (name, checksum)
            for (name, _), checksum in zip(role_inputs, checksums)
            if name is not None
        )
        for name, file_hash in named_checksums:
            h.update(b"named-input:")
            h.update(name.encode())
            h.update(b":")
            h.update(file_hash.encode())

        # Hash used containers or conda environments.
        if (
            not (job.rule.cache and job.rule.cache.omit_software)
            and job.software_env is not None
        ):
            h.update(job.software_env.hash().encode())

        # Generate hashes of dependencies, and add them in a blockchain fashion (as input to the current hash, sorted by hash value).
        hashes = await asyncio.gather(
            *[
                self._get_provenance_hash(dep)
                for dep in set(job.dag.dependencies[job].keys())
            ]
        )
        for dep_hash in sorted(hashes):
            h.update(dep_hash.encode())

        provenance_hash = h.hexdigest()

        # Store for reuse.
        self._hashes[job] = provenance_hash

        return provenance_hash
